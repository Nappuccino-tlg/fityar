/**
 * A written range - "8-12", "30-60s" - in the reader's own digits.
 *
 * Not cosmetic. Latin digits are bidi-neutral, so inside a Persian line the
 * whole run is resolved separately and comes out backwards: "8-12" renders
 * as "12-8", and "30-60s" as "60s-30". Rewriting the digits makes the line
 * one direction and the order holds.
 *
 * A trailing "s" is a unit, not a letter, so it is translated with them.
 */
export function numText(v) {
  if (v === null || v === undefined || v === '') return '';
  let out = String(v).replace(/\d+/g, (d) => num(Number(d)));
  if (LANG === 'fa') out = out.replace(/(\d|[۰-۹])s/g, '$1ث');
  return out;
}

export function countLabel(n, kind = 'item') {
  const w = COUNT_WORDS[kind] || COUNT_WORDS.item;
  return LANG === 'fa' ? `${num(n)} ${w.fa}` : `${num(n)} ${n === 1 ? w.one : w.many}`;
}

/** Pick the right language field of an object like {name, nameFa}. */
export function pick(obj, base = 'name') {
  if (!obj) return '';
  if (LANG === 'fa') return obj[base + 'Fa'] || obj[base] || '';
  return obj[base] || obj[base + 'Fa'] || '';
}
